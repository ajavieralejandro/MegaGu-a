import type { Business, BusinessHours } from '../types';

function weekdaysWithBreak(
  open = '09:00',
  close = '13:00',
  secondOpen = '17:00',
  secondClose = '20:30',
): BusinessHours[] {
  return [
    { day: 0, closed: true },
    { day: 1, open, close, secondOpen, secondClose },
    { day: 2, open, close, secondOpen, secondClose },
    { day: 3, open, close, secondOpen, secondClose },
    { day: 4, open, close, secondOpen, secondClose },
    { day: 5, open, close, secondOpen, secondClose },
    { day: 6, open, close: '13:00' },
  ];
}

function continuousDaily(open = '10:00', close = '23:00'): BusinessHours[] {
  return [0, 1, 2, 3, 4, 5, 6].map((day) => ({ day, open, close }));
}

function alwaysOpen(): BusinessHours[] {
  return [0, 1, 2, 3, 4, 5, 6].map((day) => ({
    day,
    open: '00:00',
    close: '23:59',
  }));
}

function weekdaysOnly(open = '08:00', close = '17:00'): BusinessHours[] {
  return [
    { day: 0, closed: true },
    { day: 1, open, close },
    { day: 2, open, close },
    { day: 3, open, close },
    { day: 4, open, close },
    { day: 5, open, close },
    { day: 6, closed: true },
  ];
}

